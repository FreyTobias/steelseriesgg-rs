"""Compare the PIDs in GG's device specs with the ones ssgg names, as a Markdown table.

Usage: python -I scripts/gg_parity.py <index.json> <repo-root> [<out.md>]

<index.json> is what `edevice_index.py` writes (kept outside the repo). Only PIDs and the spec's id names
reach the output. The device class is a heuristic over each device block's include chain, then its name.
"""

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

# First match wins; include-chain names are checked before the device's own name.
CLASSES = [
    ("mat", r"mousepad|qck|\bmat\b|-mat-"),
    ("mouse", r"mouse|rival|aerox|sensei|prime|kana|kinzu|ikari"),
    ("headset", r"headset|arctis|siberia|tusq|nova"),
    ("keyboard", r"keyboard|apex|\bkb\b|-kb-"),
    ("controller", r"controller|stratus|nimbus|gamepad|duo"),
    ("speaker", r"speaker|arena"),
    ("microphone", r"microphone|alias|\bmic\b"),
]
BOOTLOADER = re.compile(r"boot|updater|dfu|recovery|-bl\b|-bl-")


def classify(names):
    # MSI laptop keyboards and monitors run SteelSeries firmware under MSI ids; keep them apart.
    if any(n.startswith("msi") for n in names):
        return "msi oem"
    for kind, pattern in CLASSES:
        if any(re.search(pattern, n) for n in names):
            return kind
    return "other"


def repo_pids(root):
    text = (root / "src/devices/mod.rs").read_text(encoding="utf-8")
    block = text[text.index("pub mod product_ids") :]
    block = block[: block.index("\n}\n")]
    return {
        int(v, 16): n
        for n, v in re.findall(r"pub const (\w+): u16 = 0x([0-9A-Fa-f]{4});", block)
    }


def main(index_path, root, out):
    index = json.loads(index_path.read_text(encoding="utf-8"))
    includes = defaultdict(list)
    for device in index["devices"]:
        for pid in device["pids"]:
            includes[pid] = device["includes"]
    by_file = defaultdict(list)
    for device in index["devices"]:
        by_file[device["file"]].extend(device["includes"])

    known = repo_pids(root)
    rows = []
    for entry in index["pids"]:
        pid, name = entry["pid"], entry["name"]
        chain = includes.get(pid) or by_file.get(entry["file"], [])
        own = classify([name, entry["file"]])
        kind = (
            own if own == "msi oem" or classify(chain) == "other" else classify(chain)
        )
        rows.append(
            {
                "pid": pid,
                "name": name,
                "kind": kind,
                "boot": bool(BOOTLOADER.search(name)),
                "ssgg": pid in known,
            }
        )

    lines = [
        "# GG device parity",
        "",
        "Generated by `scripts/gg_parity.py` from GG's decrypted device specs (see `handoff.md`, section 1) and",
        "`product_ids` in `src/devices/mod.rs`. PIDs and the specs' id names only. A PID counts as in ssgg when",
        "`product_ids` names it, which says nothing about how much of the device ssgg drives. The class is a",
        "heuristic over include names. Bootloader/updater PIDs are flagged and never counted as missing.",
        "",
        "| Class | Spec PIDs | Bootloader | In ssgg | Missing |",
        "|-------|-----------|------------|---------|---------|",
    ]
    kinds = sorted(
        {r["kind"] for r in rows}, key=lambda k: -sum(r["kind"] == k for r in rows)
    )
    for kind in kinds:
        group = [r for r in rows if r["kind"] == kind]
        boot = sum(r["boot"] for r in group)
        have = sum(r["ssgg"] for r in group)
        missing = sum(not r["ssgg"] and not r["boot"] for r in group)
        lines.append(f"| {kind} | {len(group)} | {boot} | {have} | {missing} |")
    total_missing = sum(not r["ssgg"] and not r["boot"] for r in rows)
    lines.append(
        f"| **all** | **{len(rows)}** | **{sum(r['boot'] for r in rows)}** | **{sum(r['ssgg'] for r in rows)}** "
        f"| **{total_missing}** |"
    )
    absent = sorted(set(known) - {r["pid"] for r in rows})
    lines += [
        "",
        f"ssgg names {len(known)} PIDs; {len(absent)} of them are in no spec: "
        + (", ".join(f"`{p:04X}` ({known[p]})" for p in absent) or "none")
        + ".",
    ]
    for kind in kinds:
        missing = [
            r for r in rows if r["kind"] == kind and not r["ssgg"] and not r["boot"]
        ]
        if not missing:
            continue
        lines += [
            "",
            f"## Missing: {kind} ({len(missing)})",
            "",
            "| PID | Spec id |",
            "|-----|---------|",
        ]
        lines += [
            f"| `{r['pid']:04X}` | {r['name']} |"
            for r in sorted(missing, key=lambda r: r["pid"])
        ]
    text = "\n".join(lines) + "\n"
    if out:
        out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    print(f"{len(rows)} PIDs, {total_missing} missing", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    main(
        Path(sys.argv[1]),
        Path(sys.argv[2]),
        Path(sys.argv[3]) if len(sys.argv) == 4 else None,
    )
